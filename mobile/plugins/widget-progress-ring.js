/**
 * Progress ring drawables for the sYnX List Progress widget (Android).
 *
 * Android widgets can't draw custom shapes, and the built-in circular progress
 * bar starts at 3 o'clock with a fixed 32dp size. So the ring is shipped as one
 * vector drawable per whole percent (0-100) and per theme, and the widget picks
 * the one matching its percentage by resource name.
 *
 * The geometry and colors match the web app's ProgressRing (app/routes/$id.tsx):
 * a 44x44 view box, an 18-unit radius, a 3-unit stroke with round ends, a
 * slate-800/80 track, an indigo-500 arc, starting at 12 o'clock and running
 * clockwise.
 *
 * Kept as plain CommonJS so the Expo config plugin can load it at prebuild time.
 */

const RING_VIEWBOX = 44;
const RING_CENTER = 22;
const RING_RADIUS = 18;
const RING_STROKE_WIDTH = 3;

/** Web colors: track `stroke-slate-800/80`, arc `stroke-indigo-500`. */
const RING_THEMES = {
  dark: { track: "#CC1E293B", progress: "#FF6366F1" },
  // The web app is dark only. On a light widget the dark track would look heavy,
  // so light mode uses slate-200 for the track and keeps the same indigo arc.
  light: { track: "#FFE2E8F0", progress: "#FF6366F1" },
};

const RING_DRAWABLE_PREFIX = "synx_widget_ring";

function clampPercent(percent) {
  const value = Math.round(Number(percent));
  if (!Number.isFinite(value)) return 0;
  return Math.min(100, Math.max(0, value));
}

/** Android drawable resource name for a theme and percentage. */
function ringDrawableName(scheme, percent) {
  const theme = scheme === "light" ? "light" : "dark";
  return `${RING_DRAWABLE_PREFIX}_${theme}_${clampPercent(percent)}`;
}

function fmt(n) {
  return Number(n.toFixed(3)).toString();
}

/**
 * Path data for the progress arc: starts at 12 o'clock and sweeps clockwise.
 * Returns "" for 0% (only the track shows) and a full circle for 100%.
 */
function ringArcPath(percent) {
  const pct = clampPercent(percent);
  const top = `M${fmt(RING_CENTER)},${fmt(RING_CENTER - RING_RADIUS)}`;
  const r = fmt(RING_RADIUS);
  if (pct <= 0) return "";
  if (pct >= 100) {
    const bottom = `${fmt(RING_CENTER)},${fmt(RING_CENTER + RING_RADIUS)}`;
    return `${top} A${r},${r} 0 1,1 ${bottom} A${r},${r} 0 1,1 ${fmt(RING_CENTER)},${fmt(RING_CENTER - RING_RADIUS)}`;
  }
  const angle = (pct / 100) * 2 * Math.PI;
  const x = RING_CENTER + RING_RADIUS * Math.sin(angle);
  const y = RING_CENTER - RING_RADIUS * Math.cos(angle);
  const largeArc = pct > 50 ? 1 : 0;
  return `${top} A${r},${r} 0 ${largeArc},1 ${fmt(x)},${fmt(y)}`;
}

/** Full circle used for the background track. */
function ringTrackPath() {
  const r = fmt(RING_RADIUS);
  const top = `${fmt(RING_CENTER)},${fmt(RING_CENTER - RING_RADIUS)}`;
  const bottom = `${fmt(RING_CENTER)},${fmt(RING_CENTER + RING_RADIUS)}`;
  return `M${top} A${r},${r} 0 1,1 ${bottom} A${r},${r} 0 1,1 ${top}`;
}

/** Android VectorDrawable XML for one ring. */
function ringVectorXml(scheme, percent) {
  const theme = RING_THEMES[scheme === "light" ? "light" : "dark"];
  const arc = ringArcPath(percent);
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by mobile/plugins/withWidgetProgressRing.js. Do not edit. -->",
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '    android:width="56dp"',
    '    android:height="56dp"',
    `    android:viewportWidth="${RING_VIEWBOX}"`,
    `    android:viewportHeight="${RING_VIEWBOX}">`,
    "    <path",
    `        android:pathData="${ringTrackPath()}"`,
    '        android:fillColor="#00000000"',
    `        android:strokeColor="${theme.track}"`,
    `        android:strokeWidth="${RING_STROKE_WIDTH}" />`,
  ];
  if (arc) {
    lines.push(
      "    <path",
      `        android:pathData="${arc}"`,
      '        android:fillColor="#00000000"',
      `        android:strokeColor="${theme.progress}"`,
      `        android:strokeWidth="${RING_STROKE_WIDTH}"`,
      '        android:strokeLineCap="round" />'
    );
  }
  lines.push("</vector>", "");
  return lines.join("\n");
}

/** Every drawable the widget can ask for: { name, xml } for both themes, 0-100%. */
function allRingDrawables() {
  const out = [];
  for (const scheme of ["dark", "light"]) {
    for (let pct = 0; pct <= 100; pct++) {
      out.push({ name: ringDrawableName(scheme, pct), xml: ringVectorXml(scheme, pct) });
    }
  }
  return out;
}

module.exports = {
  RING_VIEWBOX,
  RING_CENTER,
  RING_RADIUS,
  RING_STROKE_WIDTH,
  RING_THEMES,
  RING_DRAWABLE_PREFIX,
  clampPercent,
  ringDrawableName,
  ringArcPath,
  ringTrackPath,
  ringVectorXml,
  allRingDrawables,
};
